#!/usr/bin/env python3
"""SnapTheJob ad engine v1.

Turns one ad.json (script + characters) plus the scene clips made in VideoExpress
into finished ads: full version, 30 s and 15 s cut-downs, each in 9:16, 1:1 and 16:9,
with burned-in captions, an optional real SnapTheJob job video, a branded end card
and .srt caption files.

  python3 stj_ad.py ad.json --check   # rules check only (run before anything else)
  python3 stj_ad.py ad.json --sheet   # write vx_sheet.md: what to type into VideoExpress
  python3 stj_ad.py ad.json --stills  # contact sheet per format, no video
  python3 stj_ad.py ad.json           # check, then render everything

Do not edit this file per ad. Everything ad-specific lives in ad.json.
"""
