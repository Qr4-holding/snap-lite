def lc(s): return s.lower().replace('’', "'")


def check(ad, quiet=False):
    """Return (errors, warnings). Errors block rendering."""
    E, W = [], []
    live = set(ad.get('live_claims', []))
    chars = ad.get('characters', {})
    scenes = ad.get('scenes', [])
    n = len(scenes)
    if ad.get('audience') not in ('trade', 'public'): E.append('audience must be "trade" or "public"')
    if not 6 <= n <= 12: W.append(f'{n} scenes: 7 to 10 usually lands near 60 s')
    for k, c in chars.items():
        for f in ('bible', 'voice', 'who'):
            if not c.get(f): E.append(f'character "{k}" has no "{f}"')
        wc = len(c.get('bible', '').split())
        if not 40 <= wc <= 75: W.append(f'character "{k}" bible is {wc} words (aim 40 to 70)')
    texts = []  # (where, text)
    for i, s in enumerate(scenes, 1):
        line = s.get('line', '')
        texts.append((f'scene {i}', line))
        lim = int(ad.get('line_limit', 99))
        if len(line) > lim: E.append(f'scene {i} line is {len(line)} characters (this VideoExpress plan allows {lim})')
        if not line.strip(): E.append(f'scene {i} has no line')
        if s.get('character') not in chars: E.append(f'scene {i} character "{s.get("character")}" is not in characters')
        if s.get('emotion') not in PALETTE: E.append(f'scene {i} emotion "{s.get("emotion")}" is not in {list(PALETTE)}')
        if not s.get('pose'): E.append(f'scene {i} has no pose (the image clause after the bible)')
        if not s.get('delivery'): E.append(f'scene {i} has no delivery direction')
        if i > 1 and s.get('emotion') == scenes[i - 2].get('emotion'):
            E.append(f'scenes {i - 1} and {i} share the emotion {s.get("emotion")} (the wave must keep moving)')
    pol = [PALETTE.get(s.get('emotion'), 0) for s in scenes]
    signs = [p for p in pol if p]
    flips = sum(1 for a, b in zip(signs, signs[1:]) if a != b)
    if flips < 3: E.append(f'the emotion wave flips {flips} times (needs at least 3 positive/negative flips)')
    if scenes and PALETTE.get(scenes[-1].get('emotion'), 0) <= 0: E.append('the last scene must be Happy, Excited or Relieved')
    first_ok = math.ceil(0.4 * n)  # product may appear from this scene number on (1-based, > 40% mark)
    for i, s in enumerate(scenes, 1):
        if re.search(PRODUCT, lc(s.get('line', ''))) and i <= first_ok:
            E.append(f'scene {i} mentions the product before the 40% mark (first allowed scene is {first_ok + 1})')
    ins = ad.get('insert')
    if ins:
        if not first_ok <= ins.get('after', 0) <= n: E.append(f'insert.after must be between {first_ok} and {n}')
        if ins.get('text'): texts.append(('insert text', ins['text']))
    ec = ad.get('end_card', {})
    if not ec.get('headline'): E.append('end_card needs a headline')
    texts += [('end card headline', ec.get('headline', '')), ('end card button', ec.get('button', ''))]
    if ec.get('headline') and ec['headline'] not in APPROVED_HEADLINES.get(ad.get('audience'), []):
        W.append(f'end card headline is not one of the approved {ad.get("audience")} headlines in the Thesis')
    for tag in ('captions', 'headlines'):
        for j, t in enumerate(ad.get('meta', {}).get(tag, []), 1): texts.append((f'meta {tag} {j}', t))
    for where, t in texts:
        low = lc(t)
        scan = low
        for ph in APPROVED_PHRASES: scan = scan.replace(ph, ' ')
        for pat in BANNED:
            if re.search(pat, scan): E.append(f'{where}: banned word /{pat}/ in "{t}"')
        for pat in COMPETITORS:
            if re.search(pat, low): E.append(f'{where}: names a competitor or platform /{pat}/ in "{t}"')
        for key, pats in GATED.items():
            if key in live: continue
            for pat in pats:
                if re.search(pat, low): E.append(f'{where}: claim "{key}" is not live yet ("{t}"). Add it to live_claims only once it is true on the site')
        if re.search(r'\d', t) and where.startswith(('scene', 'insert', 'meta', 'end')):
            if re.search(r'\d+ ?%|percent|\d', t): W.append(f'{where}: contains a figure ("{t}"); only use sourced numbers Robert supplied')
        if re.search(CONTACT, low): E.append(f'{where}: no phone numbers, emails or web addresses on screen ("{t}")')
    for name in ('cut15', 'cut30'):
        for k in ad.get(name, []):
            if not 1 <= k <= n: E.append(f'{name} lists scene {k}, which does not exist')
    if ad.get('cut15') and ad['cut15'][-1] != n and ad['cut15'][-1] < n - 1:
        W.append('cut15 should end on the reversal scene (usually the last scene)')
    if not quiet:
        for e in E: print('ERROR  ', e)
        for w in W: print('warning', w)
        print(f'check: {len(E)} errors, {len(W)} warnings; wave {pol} flips={flips}')
    return E, W


