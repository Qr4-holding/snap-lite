# ------------------------------------------------------------------ media helpers
def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: sys.exit('FFMPEG ERROR:\n' + ' '.join(cmd) + '\n' + r.stderr[-1500:])
    return r


def duration(path):
    r = run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path])
    return float(r.stdout.strip())


def has_audio(path):
    r = run(['ffprobe', '-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=index', '-of', 'csv=p=0', path])
    return bool(r.stdout.strip())


def speech_span(path):
    """First and last moment of sound, so silent heads and tails can be trimmed."""
    dur = duration(path)
    if not has_audio(path): sys.exit(f'CLIP ERROR: {path} has no audio. Re-download the Lipsync HD clip.')
    err = subprocess.run(['ffmpeg', '-i', path, '-af', 'silencedetect=noise=-38dB:d=0.15', '-f', 'null', '-'],
                         capture_output=True, text=True).stderr
    st = [float(x) for x in re.findall(r'silence_start: (-?[\d.]+)', err)]
    en = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', err)]
    a, b = 0.0, dur
    if st and st[0] <= 0.05 and en: a = en[0]
    if st and (len(en) < len(st) or en[-1] >= dur - 0.05): b = st[-1]
    if b - a < 0.6: return 0.0, dur  # could not find speech: keep the whole clip
    return max(0.0, a - LEAD), min(dur, b + TAIL)


def p(path): return path if os.path.isabs(path) else os.path.join(AD_DIR, path)


def font_file(family, weight):
    os.makedirs(FONT_CACHE, exist_ok=True)
    out = os.path.join(FONT_CACHE, f'{family}-{weight}.ttf')
    if os.path.exists(out): return out
    tmp = os.path.join(FONT_CACHE, 'pack'); shutil.rmtree(tmp, ignore_errors=True); os.makedirs(tmp)
    subprocess.run(['npm', 'pack', f'@fontsource/{family}', '--silent'], cwd=tmp, check=True, capture_output=True)
    subprocess.run(['tar', 'xzf', glob.glob(os.path.join(tmp, '*.tgz'))[0]], cwd=tmp, check=True)
    woff = os.path.join(tmp, 'package', 'files', f'{family}-latin-{weight}-normal.woff')
    from fontTools.ttLib import TTFont
    t = TTFont(woff); t.flavor = None; t.save(out)
    return out


_FC = {}
def F(kind, size):
    fam = {'display': ('bricolage-grotesque', 800), 'bold': ('work-sans', 700), 'body': ('work-sans', 400)}[kind]
    if (kind, size) not in _FC: _FC[(kind, size)] = ImageFont.truetype(font_file(*fam), size)
    return _FC[(kind, size)]


def wrap(text, font, maxw):
    lines, cur = [], ''
    for w in text.split():
        t = (cur + ' ' + w).strip()
        if font.getlength(t) <= maxw or not cur: cur = t
        else: lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines


# ------------------------------------------------------------------ captions
def chunks(line, max_words=5):
    """Split a spoken line into short caption chunks: never across a sentence end, then at commas,
    then into balanced pieces of at most max_words."""
    out = []
    for sent in re.findall(r'[^.!?]+[.!?]?', line):
        words = sent.split()
        if not words: continue
        if len(words) <= max_words: out.append(' '.join(words)); continue
        # split at commas/colons first
        parts, cur = [], []
        for w in words:
            cur.append(w)
            if re.search(r'[,;:]$', w) and len(cur) >= 2: parts.append(cur); cur = []
        if cur:
            if parts and len(cur) == 1: parts[-1] += cur
            else: parts.append(cur)
        for p in parts:
            n = -(-len(p) // max_words); size = -(-len(p) // n)  # balanced pieces
            out += [' '.join(p[i:i + size]) for i in range(0, len(p), size)]
    return out


def caption_png(text, fmt, path):
    W, H = FORMATS[fmt]
    size = {'9x16': 62, '1x1': 54, '16x9': 56}[fmt]
    maxw = {'9x16': 900, '1x1': 900, '16x9': 1400}[fmt]
    f = F('bold', size)
    lines = wrap(text, f, maxw)
    lh = int(size * 1.25); pad = int(size * 0.45)
    bw = int(max(f.getlength(l) for l in lines)) + pad * 2
    bh = lh * len(lines) + pad * 2 - int(size * 0.2)
    im = Image.new('RGBA', (bw, bh), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((0, 0, bw - 1, bh - 1), int(size * 0.45), fill=INK + (225,))
    for k, l in enumerate(lines):
        d.text(((bw - f.getlength(l)) / 2, pad + k * lh - int(size * 0.12)), l, font=f, fill=WHITE)
    im.save(path)
    cy = {'9x16': 1480, '1x1': 900, '16x9': 930}[fmt]
    return (W - bw) // 2, cy - bh // 2


# ------------------------------------------------------------------ end card
def logo(d, x, y, s=1.0):
    q = int(62 * s)
    d.rounded_rectangle((x, y, x + q, y + q), int(16 * s), fill=RED)
    d.rectangle((x + 14 * s, y + 22 * s, x + 48 * s, y + 48 * s), outline=WHITE, width=max(2, int(5 * s)))
    d.ellipse((x + 23 * s, y + 27 * s, x + 39 * s, y + 43 * s), outline=WHITE, width=max(2, int(4 * s)))


BRAND = None   # set by the narrated engine for a client-branded ad: {"logo": path, "accent": (r,g,b), "strap": str, "web": str}


def brand_mark(d_img, cx, y, width):
    """Paste the client logo centred at cx, top y, scaled to width. Returns its height."""
    lg = Image.open(BRAND['logo']).convert('RGBA')
    h = round(lg.height * width / lg.width); lg = lg.resize((round(width), h), Image.LANCZOS)
    d_img.paste(lg, (round(cx - width / 2), round(y)), lg)
    return h


def end_card_png(ec, fmt, path, reg=None):
    W, H = FORMATS[fmt]
    H0 = H
    s = {'9x16': 1.0, '1x1': 0.8, '16x9': 0.8}[fmt]
    im = Image.new('RGB', (W, H), WHITE); d = ImageDraw.Draw(im)
    blocks = []  # (height, draw_fn)
    fw = F('display', int(84 * s)); parts = (('Snap', INK), ('The', RED), ('Job', INK))
    ww = sum(fw.getlength(t) for t, _ in parts) + 100 * s
    def wordmark(y):
        x = (W - ww) / 2; logo(d, x, y + 6 * s, 1.25 * s); x += 100 * s
        for t, c in parts: d.text((x, y), t, font=fw, fill=c); x += fw.getlength(t)
    if BRAND:
        lw = min(W * 0.62, 640 * s); lh = round(lw * Image.open(BRAND['logo']).height / Image.open(BRAND['logo']).width)
        blocks.append((lh, lambda y: brand_mark(im, W / 2, y, lw)))
    else:
        blocks.append((int(110 * s), wordmark))
    ACC = BRAND['accent'] if BRAND else RED
    fh = F('display', int(78 * s)); hl = wrap(ec['headline'], fh, W - 160)
    if len(hl) > 1:  # balance the lines so no word sits alone on the last line
        k, mw = len(hl), fh.getlength(ec['headline']) / len(hl)
        while len(wrap(ec['headline'], fh, mw)) > k: mw += 10
        hl = wrap(ec['headline'], fh, mw)
    def headline(y):
        for k, l in enumerate(hl): d.text(((W - fh.getlength(l)) / 2, y + k * int(92 * s)), l, font=fh, fill=INK)
    blocks.append((int(92 * s) * len(hl), headline))
    if ec.get('button'):
        fb = F('display', int(52 * s)); bw = fb.getlength(ec['button']) + 120 * s; bh = int(112 * s)
        def button(y):
            x = (W - bw) / 2; d.rounded_rectangle((x, y, x + bw, y + bh), bh // 2, fill=ACC)
            d.text((x + 60 * s, y + 20 * s), ec['button'], font=fb, fill=WHITE)
        blocks.append((bh, button))
    fs = F('display', int(46 * s)); sp = (('Before, ', RED), ('After, ', INK), ('Share.', RED))
    if BRAND:
        sp = ((BRAND.get('strap', ''), INK),)
        if BRAND.get('phone'):   # big, the main call to action on a client card
            fp = F('display', int(104 * s))
            blocks.append((int(116 * s), lambda y: d.text(((W - fp.getlength(BRAND['phone'])) / 2, y), BRAND['phone'], font=fp, fill=ACC)))
        if BRAND.get('email'):
            fe = F('bold', int(46 * s))
            blocks.append((int(54 * s), lambda y: d.text(((W - fe.getlength(BRAND['email'])) / 2, y), BRAND['email'], font=fe, fill=INK)))
        if BRAND.get('web'):
            fwb = F('bold', int(40 * s))
            blocks.append((int(48 * s), lambda y: d.text(((W - fwb.getlength(BRAND['web'])) / 2, y), BRAND['web'], font=fwb, fill=ACC)))
    def strap(y):
        x = (W - sum(fs.getlength(t) for t, _ in sp)) / 2
        for t, c in sp: d.text((x, y), t, font=fs, fill=c); x += fs.getlength(t)
    blocks.append((int(60 * s), strap))
    # registration pill: centred, accent colour, white display font 32 px, its bottom edge 40 px above the bottom of the frame.
    # On a narrow frame the text goes on two lines (name, then "Registered carrier · number") rather than running off the edge.
    pill = None
    if reg and (reg.get('end_text') or reg.get('text')):
        fr_ = F('display', 32); txt = reg.get('end_text') or reg['text']       # one line: "Registered carrier · <number>"
        lh_ = int(32 * 1.3); ph = lh_ + 28; pw = int(fr_.getlength(txt)) + 56
        pill = ([txt], fr_, lh_, ph, pw)
    gap = int(70 * s); total = sum(h for h, _ in blocks) + gap * (len(blocks) - 1)
    if total > H * 0.86:   # crowded card: tighten the gaps to fit
        gap = max(int(18 * s), int((H * 0.86 - sum(h for h, _ in blocks)) / max(1, len(blocks) - 1)))
        total = sum(h for h, _ in blocks) + gap * (len(blocks) - 1)
    y = (H - total) // 2
    if pill:   # the content stays where it was; it only moves up, by the least needed, if it would touch the pill
        over = (y + total) - (H0 - 40 - pill[3] - 24)
        if over > 0: y -= over
    for h, fn in blocks: fn(y); y += h + gap
    H = H0
    d.rectangle((0, H - int(14 * s), W, H), fill=ACC)
    if pill:
        lines_, fr_, lh_, ph, pw = pill; x0 = (W - pw) // 2; y0 = H - 40 - ph
        d.rounded_rectangle((x0, y0, x0 + pw, y0 + ph), ph // 2 if len(lines_) == 1 else 28, fill=ACC)
        for k, l in enumerate(lines_): d.text(((W - fr_.getlength(l)) / 2, y0 + 14 + k * lh_), l, font=fr_, fill=WHITE)
    im.save(path)


