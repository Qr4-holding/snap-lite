def norm_args(w=1080, h=1920):
    return ['-vf', f'scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={FPS},setsar=1,format=yuv420p',
            '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '19', '-c:a', 'aac', '-b:a', '160k', '-ar', str(SR), '-ac', '2']


def loudness(path, a, b):
    err = subprocess.run(['ffmpeg', '-ss', f'{a:.3f}', '-to', f'{b:.3f}', '-i', path, '-af', 'ebur128', '-f', 'null', '-'],
                         capture_output=True, text=True).stderr
    m = re.findall(r'I:\s+(-?[\d.]+) LUFS', err)
    return float(m[-1]) if m else None


def cut_in_sync(src, a, b, out, target_lufs=-16):
    """Cut [a, b] so picture and sound are EXACTLY the same length (whole frames), so joins never drift.
    Loudness is matched with a fixed gain (no loudnorm, which can shift audio timing)."""
    d = max(1, round((b - a) * FPS)) / FPS
    lu = loudness(src, a, a + d)
    gain = 0.0 if lu is None or lu < -60 else max(-12.0, min(12.0, target_lufs - lu))
    w, h = 1080, 1920
    flt = (f'[0:v]trim=start={a:.4f}:end={a + d:.4f},setpts=PTS-STARTPTS,'
           f'scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={FPS},setsar=1,format=yuv420p[v];'
           f'[0:a]atrim=start={a:.4f}:end={a + d:.4f},asetpts=PTS-STARTPTS,aresample={SR},volume={gain:.2f}dB,'
           f'alimiter=limit=0.89,apad=whole_dur={d:.4f},atrim=end={d:.4f}[a]')
    run(['ffmpeg', '-y', '-i', src, '-filter_complex', flt, '-map', '[v]', '-map', '[a]', '-frames:v', str(round(d * FPS)),
         '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '19', '-c:a', 'aac', '-b:a', '160k', '-ar', str(SR), '-ac', '2', out])


def build_master_segments(ad, work):
    """9:16 uncaptioned master per scene (+ insert), trimmed and loudness-matched."""
    segs = []
    for i, s in enumerate(ad['scenes'], 1):
        src = p(s.get('clip') or f'clips/s{i:02d}.mp4')
        if not os.path.exists(src): sys.exit(f'CLIP ERROR: scene {i} clip not found: {src}')
        a, b = speech_span(src)
        out = os.path.join(work, f'm_s{i:02d}.mp4')
        cut_in_sync(src, a, b, out, target_lufs=-16)
        segs.append({'kind': 'scene', 'n': i, 'file': out, 'dur': duration(out), 'line': s['line']})
        ins = ad.get('insert')
        if ins and ins.get('after') == i:
            isrc = p(ins['video'])
            if not os.path.exists(isrc): sys.exit(f'INSERT ERROR: {isrc} not found')
            secs = min(float(ins.get('seconds', 6)), duration(isrc))
            iout = os.path.join(work, 'm_insert.mp4')
            if has_audio(isrc) and not ins.get('mute'):
                cut_in_sync(isrc, 0.0, secs, iout, target_lufs=-18)
            else:
                run(['ffmpeg', '-y', '-t', f'{secs:.3f}', '-i', isrc, '-f', 'lavfi', '-t', f'{secs:.3f}',
                     '-i', f'anullsrc=r={SR}:cl=stereo', '-map', '0:v', '-map', '1:a', '-shortest'] + norm_args() + [iout])
            segs.append({'kind': 'insert', 'file': iout, 'dur': duration(iout), 'line': ins.get('text', '')})
    return segs


def format_segment(seg, fmt, work, ad):
    """Crop or pad the 9:16 master to fmt and burn captions. End cards are drawn per format."""
    W, H = FORMATS[fmt]
    tag = f"{seg['kind']}{seg.get('n', '')}_{fmt}"
    out = os.path.join(work, f'f_{tag}.mp4')
    if os.path.exists(out): return out, seg['dur']
    if seg['kind'] == 'end':
        png = os.path.join(work, f'end_{fmt}.png'); end_card_png(ad['end_card'], fmt, png)
        run(['ffmpeg', '-y', '-loop', '1', '-t', str(END_SECONDS), '-i', png, '-f', 'lavfi', '-t', str(END_SECONDS),
             '-i', f'anullsrc=r={SR}:cl=stereo', '-map', '0:v', '-map', '1:a', '-shortest'] + norm_args(W, H) + [out])
        return out, END_SECONDS
    if fmt == '9x16': base = '[0:v]null[b]'
    elif fmt == '1x1': base = f'[0:v]crop=1080:1080:0:{int((1920 - 1080) * SQUARE_Y)}[b]'
    else: base = ('[0:v]split[x][y];[x]scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080,'
                  'gblur=sigma=40,eq=brightness=-0.10[bg];[y]scale=608:1080,setsar=1[fg];[bg][fg]overlay=(W-w)/2:0[b]')
    inputs, filt, last = ['-i', seg['file']], [base], '[b]'
    cues = caption_cues(seg)
    for k, (t0, t1, text) in enumerate(cues):
        png = os.path.join(work, f'cap_{tag}_{k}.png')
        x, y = caption_png(text, fmt, png)
        inputs += ['-i', png]
        filt.append(f"{last}[{k + 1}:v]overlay={x}:{y}:enable='between(t,{t0:.3f},{t1:.3f})'[c{k}]")
        last = f'[c{k}]'
    filt.append(f'{last}setsar=1,format=yuv420p[v]')
    run(['ffmpeg', '-y'] + inputs + ['-filter_complex', ';'.join(filt), '-map', '[v]', '-map', '0:a',
         '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '19', '-r', str(FPS), '-c:a', 'copy', out])
    return out, seg['dur']


def caption_cues(seg):
    """(start, end, text) for one segment, timed across its speech by character share."""
    text = seg.get('line', '').strip()
    if not text: return []
    if seg['kind'] == 'insert': return [(0.2, seg['dur'] - 0.1, text)]
    parts = chunks(text)
    a, b = LEAD, max(LEAD + 0.5, seg['dur'] - TAIL + 0.05)
    total = sum(len(x) for x in parts); t, cues = a, []
    for x in parts:
        d = (b - a) * len(x) / total
        cues.append((t, t + d, x)); t += d
    return cues


def concat(files, out):
    inp = []
    for f in files: inp += ['-i', f]
    n = len(files)
    parts = []
    for i, f in enumerate(files):  # sound trimmed/padded to exactly the picture's length, so no drift at joins
        nf = int(run(['ffprobe', '-v', 'error', '-count_frames', '-select_streams', 'v', '-show_entries',
                      'stream=nb_read_frames', '-of', 'csv=p=0', f]).stdout.strip())
        d = nf / FPS
        parts.append(f'[{i}:v]setsar=1,trim=end_frame={nf},setpts=PTS-STARTPTS[v{i}];'
                     f'[{i}:a]asetpts=PTS-STARTPTS,apad=whole_dur={d:.4f},atrim=end={d:.4f}[a{i}];')
    flt = ''.join(parts) + ''.join(f'[v{i}][a{i}]' for i in range(n)) + f'concat=n={n}:v=1:a=1[v][a]'
    run(['ffmpeg', '-y'] + inp + ['-filter_complex', flt, '-map', '[v]', '-map', '[a]', '-c:v', 'libx264',
         '-preset', 'medium', '-crf', '20', '-pix_fmt', 'yuv420p', '-r', str(FPS), '-c:a', 'aac', '-b:a', '160k',
         '-movflags', '+faststart', out])


def srt(segs, path):
    def ts(x):
        ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
        return f'{h:02d}:{m:02d}:{s:02d},{ms:03d}'
    rows, t0, k = [], 0.0, 1
    for seg in segs:
        for a, b, text in caption_cues(seg):
            rows.append(f'{k}\n{ts(t0 + a)} --> {ts(t0 + b)}\n{text}\n'); k += 1
        t0 += seg['dur']
    open(path, 'w').write('\n'.join(rows))


def variants(ad, segs):
    end = {'kind': 'end', 'file': None, 'dur': END_SECONDS, 'line': ''}
    out = {'full': segs + [end]}
    by_n = {s['n']: s for s in segs if s['kind'] == 'scene'}
    ins = [s for s in segs if s['kind'] == 'insert']
    for name in ('cut30', 'cut15'):
        picks = ad.get(name)
        if not picks: continue
        lst = []
        for k in picks:
            lst.append(by_n[k])
            if name == 'cut30' and ins and ad['insert']['after'] == k: lst.append(ins[0])
        out[name] = lst + [end]
    return out


def main():
    global AD_DIR
    if len(sys.argv) < 2: sys.exit(__doc__)
    jp = sys.argv[1]; AD_DIR = os.path.dirname(os.path.abspath(jp))
    ad = json.load(open(jp))
    errors, _ = check(ad, quiet=False)
    if '--check' in sys.argv: sys.exit(1 if errors else 0)
    if errors: sys.exit('Fix the errors above before making the sheet or rendering.')
    if '--sheet' in sys.argv: return sheet(ad)
    work = os.path.join(AD_DIR, 'work'); os.makedirs(work, exist_ok=True)
    for f in glob.glob(os.path.join(work, 'f_*.mp4')): os.remove(f)
    outdir = p(ad.get('out', 'out')); os.makedirs(outdir, exist_ok=True)
    segs = build_master_segments(ad, work)
    fmts = ad.get('formats', list(FORMATS))
    if '--stills' in sys.argv:
        for fmt in fmts:
            ims = []
            for seg in segs + [{'kind': 'end', 'dur': END_SECONDS, 'line': ''}]:
                f, d = format_segment(seg, fmt, work, ad)
                cues = caption_cues(seg)
                t = (cues[0][0] + cues[0][1]) / 2 if cues else d / 2
                png = f.replace('.mp4', '.png')
                run(['ffmpeg', '-y', '-ss', f'{t:.2f}', '-i', f, '-frames:v', '1', png])
                im = Image.open(png); im.thumbnail((360, 360)); ims.append(im)
            cols = min(6, len(ims)); rows = math.ceil(len(ims) / cols)
            cw = max(i.width for i in ims); ch = max(i.height for i in ims)
            sheet_im = Image.new('RGB', (cw * cols, ch * rows), (200, 200, 200))
            for k, im in enumerate(ims): sheet_im.paste(im, ((k % cols) * cw, (k // cols) * ch))
            sp = os.path.join(AD_DIR, f'stills_{fmt}.png'); sheet_im.save(sp); print('stills ->', sp)
        return
    made = []
    for name, lst in variants(ad, segs).items():
        for fmt in fmts:
            files = [format_segment(s, fmt, work, ad)[0] for s in lst]
            out = os.path.join(outdir, f"{ad['id']}_{name}_{fmt}.mp4")
            concat(files, out); made.append(out)
            if fmt == fmts[0]: srt(lst, os.path.join(outdir, f"{ad['id']}_{name}.srt"))
            print(f'done {out}  {duration(out):.1f}s')
    print(f'{len(made)} videos in {outdir}')


if __name__ == '__main__':
    main()
