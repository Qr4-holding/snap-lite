#!/usr/bin/env python3
"""SnapTheJob / CleanUpSnap video engine v3.1 (server copy of the snapthejob-video skill engine, plus a per-brand block).
Runs on the site server: python3 video/engine.py job.json. job.json may carry "brand": {red, ink, site, name_parts, strapline, fonts{display,bold,body}}.
SnapTheJob video engine v3. Portrait 1080x1920 job video:
split before/after cover with play button, then before/(during)/after reveal and end card.
Optional voiceover. Makes TWO versions of every job:
  <out>.mp4       SOCIAL version: SnapTheJob bar on top, job-type strip and Get a quote button
                  at the bottom. For Facebook, Instagram, TikTok, YouTube.
  <out>_site.mp4  WEBSITE version: clean full-screen photos, no bars, no baked-in buttons
                  (the SnapTheJob player shows its own). Upload THIS one at snapthejob.co.uk/admin/jobs.
Also saves covers: <out>_cover.jpg and <out>_site_cover.jpg.

  python3 stj_video.py job.json            # render BOTH versions (social + website)
  python3 stj_video.py job.json --social   # social version only
  python3 stj_video.py job.json --site     # website version only
  python3 stj_video.py job.json --stills [--site]  # preview contact sheet (stills_sheet.png), no video
  python3 stj_video.py job.json --plan     # print timings only

Do not edit this file per job. Everything job-specific lives in job.json.
"""
import json, os, sys, glob, shutil, subprocess, re
from PIL import Image, ImageDraw, ImageFont, ImageFilter

W, H, FPS = 1080, 1920, 25
TOP, BOT = 150, 152
PH = H - TOP - BOT
LABEL_Y = 0  # extra drop for labels (website version leaves room for the player's back button)
INK, WHITE, RED, GREY = (31, 33, 36), (255, 255, 255), (217, 56, 30), (176, 182, 190)
# label: (background, text colour)
LABEL_STYLE = {'BEFORE': (WHITE, RED), 'DURING': (INK, WHITE), 'AFTER': (RED, WHITE)}
WIPE, XF, HOLD, END_SILENT, VO_OFFSET = 1.0, 0.4, 2.6, 3.2, 0.3
COVER, COVER_XF = 1.2, 0.35   # cover shown first, then cross-fades into the before photo
FONT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fonts')
JOB_DIR = '.'
BRAND = {  # overridden by job.json "brand"
    'site': 'SnapTheJob.co.uk',
    'name_parts': [['Snap', 'white'], ['The', 'red'], ['Job', 'white']],
    'strapline': [['Before, ', 'red'], ['After, ', 'white'], ['Share.', 'red']],
    'fonts': {'display': 'bricolage-grotesque-800', 'bold': 'work-sans-700', 'body': 'work-sans-400'}
}

# ---------------------------------------------------------------- helpers
def ease(t): t = max(0, min(1, t)); return 1 - (1 - t) ** 3
def prog(t, a, d): return max(0.0, min(1.0, (t - a) / d))

def font_file(name):
    f = os.path.join(FONT_DIR, name + '.ttf')
    if not os.path.exists(f): sys.exit(f'FONT ERROR: {f} missing')
    return f

_FC = {}
def F(kind, size):
    key = (kind, size)
    if key not in _FC: _FC[key] = ImageFont.truetype(font_file(BRAND['fonts'][kind]), size)
    return _FC[key]

def col(c): return {'white': WHITE, 'red': RED, 'ink': INK, 'grey': GREY}.get(c, WHITE)
def hexcol(h): h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def apply_brand(b):
    global RED, INK, LABEL_STYLE
    BRAND.update({k: v for k, v in b.items() if k != 'fonts'})
    if b.get('fonts'): BRAND['fonts'].update(b['fonts'])
    if b.get('red'): RED = hexcol(b['red'])
    if b.get('ink'): INK = hexcol(b['ink'])
    LABEL_STYLE = {'BEFORE': (WHITE, RED), 'DURING': (INK, WHITE), 'AFTER': (RED, WHITE)}

def p(path): return path if os.path.isabs(path) else os.path.join(JOB_DIR, path)

# ---------------------------------------------------------------- photos
def raw_photo(ph):
    im = Image.open(p(ph['src'])).convert('RGB')
    w, h = im.size
    c = ph.get('crop')  # [left, top, right, bottom] as 0-1 fractions, optional
    if c: im = im.crop((int(c[0] * w), int(c[1] * h), int(c[2] * w), int(c[3] * h)))
    return im

def load_photo(ph):
    im = raw_photo(ph)
    s = max(W / im.width, PH / im.height) * 1.06
    return im.resize((int(im.width * s), int(im.height * s)), Image.LANCZOS)

def full_frame(im):
    """Cover-fit to the whole 1080x1920 frame, anchored to the top."""
    s = max(W / im.width, H / im.height)
    im = im.resize((int(im.width * s), int(im.height * s)), Image.LANCZOS)
    x = (im.width - W) // 2
    return im.crop((x, 0, x + W, H))

def view(im, z):
    """Crop at zoom z (1.0..1.04), anchored to the TOP so labels at the top never get cut."""
    sw = min(im.width, im.height * W / PH) / (1.06 * z)
    sh = sw * PH / W
    cx = im.width / 2
    box = (int(cx - sw / 2), 0, int(cx + sw / 2), int(sh))
    return im.crop(box).resize((W, PH), Image.BILINEAR)

def draw_label(img, text, x=0, y=24, size=84, right=False, radius=0):
    d = ImageDraw.Draw(img); f = F('display', size)
    bg, fg = LABEL_STYLE.get(text.split()[0], (WHITE, INK))
    tw = f.getlength(text); pw = tw + size * 0.66; ph = size * 1.38
    x0 = x - pw if right else x
    d.rounded_rectangle((x0, y, x0 + pw, y + ph), radius, fill=bg)
    d.text((x0 + size * 0.33, y + size * 0.1), text, font=f, fill=fg)
    return img

def make_cover(before_ph, after_ph):
    """Split cover: left half before, right half after, labels, play button."""
    A = full_frame(raw_photo(before_ph)); B = full_frame(raw_photo(after_ph))
    c = A.copy(); c.paste(B.crop((W // 2, 0, W, H)), (W // 2, 0))
    d = ImageDraw.Draw(c); d.rectangle((W // 2 - 5, 0, W // 2 + 5, H), fill=WHITE)
    draw_label(c, 'BEFORE', x=32, y=40 + LABEL_Y, size=64, radius=14)
    draw_label(c, 'AFTER', x=W - 32, y=40 + LABEL_Y, size=64, right=True, radius=14)
    c = c.convert('RGBA'); cx, cy, r = W // 2, H // 2, 118
    sh = Image.new('RGBA', c.size, (0, 0, 0, 0))
    ImageDraw.Draw(sh).ellipse((cx - r, cy - r + 14, cx + r, cy + r + 14), fill=(0, 0, 0, 110))
    c.alpha_composite(sh.filter(ImageFilter.GaussianBlur(18)))
    d = ImageDraw.Draw(c)
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(255, 255, 255, 240))
    t = 58; d.polygon([(cx - t * 0.7, cy - t), (cx - t * 0.7, cy + t), (cx + t * 1.05, cy)], fill=INK + (255,))
    return c.convert('RGB')

# ---------------------------------------------------------------- chrome
def logo(d, x, y, s=1.0):
    q = int(62 * s)
    d.rounded_rectangle((x, y, x + q, y + q), int(16 * s), fill=RED)
    d.rectangle((x + 14 * s, y + 22 * s, x + 48 * s, y + 48 * s), outline=WHITE, width=max(2, int(5 * s)))
    d.ellipse((x + 23 * s, y + 27 * s, x + 39 * s, y + 43 * s), outline=WHITE, width=max(2, int(4 * s)))

def chrome(img, cfg):
    if cfg.get('_site'): return img  # website version: the site shows its own buttons
    d = ImageDraw.Draw(img)
    d.rectangle((0, 0, W, TOP), fill=INK)
    logo(d, 48, 38)
    f = F('display', 46); x = 128
    for part, c in BRAND['name_parts']:
        d.text((x, 30), part, font=f, fill=col(c)); x += f.getlength(part)
    fs = F('display', 22); x = 130
    for part, c in BRAND['strapline']:
        d.text((x, 92), part, font=fs, fill=col(c)); x += fs.getlength(part)
    s = 'Posted by ' + cfg['business'] + ('  ·  AI voice' if (cfg.get('ai_voice') or (cfg.get('voice') and not cfg.get('voice_free'))) else '')
    fb = F('body', 26)
    d.text((W - 48 - fb.getlength(s), 62), s, font=fb, fill=GREY)
    d.rectangle((0, H - BOT, W, H), fill=INK)
    d.text((48, H - BOT + 54), cfg['job_type'], font=F('bold', 34), fill=WHITE)
    pw, ph = 300, 84; px, py = W - 48 - pw, H - BOT + (BOT - ph) // 2
    d.rounded_rectangle((px, py, px + pw, py + ph), 42, fill=RED)
    q = 'Get a quote'; fq = F('display', 38)
    d.text((px + (pw - fq.getlength(q)) / 2, py + 14), q, font=fq, fill=WHITE)
    return img

def end_frame(t, cfg):
    img = Image.new('RGBA', (W, H), INK + (255,))
    def txt(y, s, f, fill, a0):
        a = ease(prog(t, a0, 0.5))
        if a <= 0: return
        L = Image.new('RGBA', (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(L)
        d.text(((W - f.getlength(s)) / 2, y + (1 - a) * 20), s, font=f, fill=fill + (int(255 * a),))
        img.alpha_composite(L)
    name = cfg['business']; fs = 96
    while F('display', fs).getlength(name) > W - 120 and fs > 50: fs -= 4
    txt(560, name, F('display', fs), WHITE, 0.1)
    if cfg.get('services_line'): txt(690, cfg['services_line'], F('body', 40), GREY, 0.35)
    a = ease(prog(t, 0.6, 0.5))
    if a > 0:
        L = Image.new('RGBA', (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(L)
        pw, ph = 520, 120; px, py = (W - pw) // 2, 860 + (1 - a) * 20
        if cfg.get('_site'): a = 0  # website version: no quote button baked in
    if a > 0:
        d.rounded_rectangle((px, py, px + pw, py + ph), 60, fill=RED + (int(255 * a),))
        fq = F('display', 56); q = 'Get a quote'
        d.text((px + (pw - fq.getlength(q)) / 2, py + 22), q, font=fq, fill=WHITE + (int(255 * a),))
        img.alpha_composite(L)
    if not cfg.get('_site'): txt(1060, 'on ' + BRAND['site'], F('body', 38), WHITE, 0.85)
    a = ease(prog(t, 1.0, 0.5))
    if a > 0:
        L = Image.new('RGBA', (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(L)
        f = F('display', 44); parts = [(t, col(c)) for t, c in BRAND['strapline']]
        x = (W - sum(f.getlength(s) for s, _ in parts)) / 2
        for s, c in parts:
            d.text((x, 1240 + (1 - a) * 16), s, font=f, fill=c + (int(255 * a),)); x += f.getlength(s)
        img.alpha_composite(L)
    if not cfg.get('_site'): txt(1680, 'Posted by the business. Real job photos.', F('body', 26), GREY, 1.1)
    return img.convert('RGB')

# ---------------------------------------------------------------- timing
def voice_line_starts(mp3, n_lines):
    """Find where each script line starts: the (n_lines-1) longest pauses are the line breaks."""
    r = subprocess.run(['ffmpeg', '-i', mp3, '-af', 'silencedetect=noise=-35dB:d=0.25', '-f', 'null', '-'],
                       capture_output=True, text=True).stderr
    starts = [float(x) for x in re.findall(r'silence_start: ([\d.]+)', r)]
    ends = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', r)]
    dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', mp3],
                               capture_output=True, text=True).stdout.strip())
    gaps = [(e - s, s, e) for s, e in zip(starts, ends) if s > 0.2 and e < dur - 0.2]
    if len(gaps) < n_lines - 1:
        sys.exit(f'VOICE ERROR: found {len(gaps)} pauses but need {n_lines - 1}. '
                 'Regenerate the voice with a blank line between script lines, or check the script has '
                 f'{n_lines} lines (one per photo plus one for the end card).')
    br = sorted(sorted(gaps, reverse=True)[:n_lines - 1], key=lambda g: g[1])
    return [0.0] + [g[2] for g in br], dur

def plan(cfg):
    """Times are measured from the start of the reveal (after the cover)."""
    n = len(cfg['photos'])
    if cfg.get('voice') and cfg.get('voice_free'):
        # a mic recording: no line timing; photos share the voice evenly and the end card follows
        dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p(cfg['voice'])],
                                   capture_output=True, text=True).stdout.strip() or 0)
        P = max(n * HOLD, dur + VO_OFFSET - 2.0)
        starts = [i * P / n for i in range(n)]
        photo_end = P + 0.2
        end_dur = max(END_SILENT, dur + VO_OFFSET + 1.0 - photo_end + XF)
    elif cfg.get('voice'):
        ls, dur = voice_line_starts(p(cfg['voice']), n + 1)
        starts = [0.0] + [x + VO_OFFSET for x in ls[1:n]]
        photo_end = ls[n] + VO_OFFSET
        if photo_end - starts[-1] < WIPE + 0.8: photo_end = starts[-1] + WIPE + 0.8
        total = dur + VO_OFFSET + 1.0
        end_dur = total - photo_end + XF
    else:
        starts = [i * HOLD for i in range(n)]
        photo_end = starts[-1] + HOLD + 0.2
        end_dur = END_SILENT
    return starts, photo_end, end_dur

# ---------------------------------------------------------------- render
def main():
    global JOB_DIR
    if len(sys.argv) < 2: sys.exit(__doc__)
    jp = sys.argv[1]; JOB_DIR = os.path.dirname(os.path.abspath(jp))
    if not any(f in sys.argv for f in ('--site', '--social', '--stills', '--plan')):
        # default: make both versions, one after the other
        for flag in ('--social', '--site'):
            r = subprocess.run([sys.executable, os.path.abspath(__file__), jp, flag])
            if r.returncode != 0: sys.exit(r.returncode)
        return
    cfg = json.load(open(jp))
    if cfg.get('brand'): apply_brand(cfg['brand'])
    if '--site' in sys.argv:  # clean website version: full-frame photos, no bars, no baked buttons
        global PH, TOP, LABEL_Y
        PH, TOP, LABEL_Y = H, 0, 150
        cfg['_site'] = True
        cfg['out'] = os.path.splitext(cfg['out'])[0] + '_site.mp4'
    n = len(cfg['photos'])
    if not 2 <= n <= 5: sys.exit('PHOTO ERROR: use 2 to 5 photos (before first, after last).')
    starts, photo_end, end_dur = plan(cfg)
    reveal = photo_end + end_dur - XF
    total = COVER + reveal
    print('cover', COVER, 's; photo starts', [round(COVER + s, 2) for s in starts], 'end card at',
          round(COVER + photo_end - XF, 2), 'total', round(total, 1), 's')
    if '--plan' in sys.argv: return
    cover = make_cover(cfg['photos'][0], cfg['photos'][-1])
    photos = []
    for ph in cfg['photos']:
        photos.append((load_photo(ph), ph.get('label') if cfg.get('add_labels', True) else None))

    def shot(i, z):
        v = view(photos[i][0], z)
        return draw_label(v, photos[i][1], y=24 + LABEL_Y) if photos[i][1] else v

    def photo_frame(t):
        i = max(k for k, s in enumerate(starts) if s <= t)
        nxt = starts[i + 1] if i + 1 < n else photo_end
        z = 1.0 + 0.04 * min(1, max(0, t - starts[i]) / max(0.1, nxt - starts[i]))
        if i > 0 and t - starts[i] < WIPE:
            pr = ease((t - starts[i]) / WIPE); x = int(W * pr)
            ph = shot(i - 1, 1.04); a = shot(i, 1.0)
            ph.paste(a.crop((0, 0, x, PH)), (0, 0))
            ImageDraw.Draw(ph).rectangle((x - 3, 0, x + 3, PH), fill=WHITE)
        else:
            ph = shot(i, z)
        img = Image.new('RGB', (W, H), INK); img.paste(ph, (0, TOP))
        return chrome(img, cfg)

    def reveal_frame(T):
        a = photo_end - XF
        if T < a: return photo_frame(T)
        if T < photo_end: return Image.blend(photo_frame(T), end_frame(T - a, cfg), (T - a) / XF)
        return end_frame(T - a, cfg)

    def frame(T):
        if T < COVER - COVER_XF: return cover
        if T < COVER: return Image.blend(cover, reveal_frame(0), (T - (COVER - COVER_XF)) / COVER_XF)
        return reveal_frame(T - COVER)

    out = p(cfg['out'])
    cover_path = os.path.splitext(out)[0] + '_cover.jpg'
    cover.save(cover_path, quality=92)

    if '--stills' in sys.argv:
        ts = [0.3] + [COVER + 0.5] + [COVER + s + WIPE * 0.5 for s in starts[1:]] + \
             [COVER + s + WIPE + 0.3 for s in starts[1:]] + [COVER + photo_end + 1.6]
        ts = sorted(set(round(t, 2) for t in ts))
        ims = [frame(t).resize((270, 480)) for t in ts]
        sheet = Image.new('RGB', (270 * len(ims), 480))
        for k, im in enumerate(ims): sheet.paste(im, (k * 270, 0))
        sp = os.path.join(JOB_DIR, 'stills_sheet.png'); sheet.save(sp); print('stills', ts, '->', sp); return

    silent = out + '.silent.mp4'
    pr = subprocess.Popen(['ffmpeg', '-y', '-loglevel', 'error', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', f'{W}x{H}', '-r', str(FPS), '-i', '-',
                           '-c:v', 'libx264', '-preset', os.environ.get('STJ_PRESET', 'medium'), '-crf', '22', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', silent], stdin=subprocess.PIPE)
    for k in range(int(total * FPS)): pr.stdin.write(frame(k / FPS).tobytes())
    pr.stdin.close(); pr.wait()
    if cfg.get('voice'):
        ms = int((COVER + VO_OFFSET) * 1000)
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', silent, '-i', p(cfg['voice']),
                        '-filter_complex', f'[1]adelay={ms}|{ms},apad[a]', '-map', '0:v', '-map', '[a]',
                        '-c:v', 'copy', '-c:a', 'aac', '-b:a', '160k', '-shortest', '-movflags', '+faststart', out], check=True)
        os.remove(silent)
    else:
        os.replace(silent, out)
    print('done', out, round(total, 1), 's  cover:', cover_path)

if __name__ == '__main__':
    main()
